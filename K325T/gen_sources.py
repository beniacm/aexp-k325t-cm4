#!/usr/bin/env python3
"""Write sources.tcl: the R6 project's synthesis sources (CORE/CORE-R6.xpr) with their
file types, minus the R6 board top, CORE/vhdl/clk.vhd replaced by K325T/stall_clk.vhd, plus the K325T files and the two files shared with
the MEGA65 core port (sd_emu, rk_bridge from ../mega65-core)."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
x = open(os.path.join(root, 'CORE/CORE-R6.xpr')).read()
a = x.index('<FileSet Name="sources_1"'); b = x.index('</FileSet>', a)
out = ['# GENERATED by K325T/gen_sources.py -- do not edit']
for p, body in re.findall(r'<File Path="([^"]+)">(.*?)</File>', x[a:b], re.S):
    if p.endswith('top_mega65-r6.vhd') or 'synthesis' not in body:
        continue
    path = os.path.normpath(p.replace('$PPRDIR', os.path.join(root, 'CORE')))
    # the K325T's stoppable clock (stall_clk.vhd, entity clk) replaces the upstream clock file
    if path.endswith(os.path.join('CORE', 'vhdl', 'clk.vhd')):
        path = os.path.join(here, 'stall_clk.vhd')
    assert os.path.exists(path), path
    m = re.search(r'SFType="([^"]+)"', body)
    ext = path.rsplit('.', 1)[-1]
    ft = {'VHDL2008': 'VHDL 2008', 'SVerilog': 'SystemVerilog'}.get(m.group(1) if m else '',
         {'vhd': 'VHDL', 'vhdl': 'VHDL', 'v': 'Verilog', 'sv': 'SystemVerilog'}[ext])
    out.append('add_files -norecurse {%s}; set_property FILE_TYPE {%s} [get_files {%s}]' % (path, ft, path))
# K325T: the TG68K (68020) that cpu_wrapper.v instantiates again (AExp's R6 project leaves it
# out); plain VHDL, package first
tg = os.path.join(root, 'CORE/Minimig_MiSTerMEGA65/rtl/tg68k')
for f in ['TG68K_Pack.vhd', 'TG68K_ALU.vhd', os.path.join(here, 'cpu020/TG68K_MMU030.vhd'), 'TG68KdotC_Kernel.vhd']:
    f = os.path.join(tg, f)
    assert os.path.exists(f), f
    out.append('add_files -norecurse {%s}; set_property FILE_TYPE {VHDL} [get_files {%s}]' % (f, f))
# K325T stage 3: MiSTer's 68EC020 cycle model (cpu_cycles.v; its tables K325T/cpu020/*.mem are read
# with $readmemh relative to the synthesis run directory)
f = os.path.join(here, 'cpu020/cpu_cycles.v')
out.append('add_files -norecurse {%s}; set_property FILE_TYPE {Verilog} [get_files {%s}]' % (f, f))
mc = os.path.normpath(os.path.join(root, '../mega65-core/src/vhdl'))
for f in [os.path.join(here, 'top_qmtech_k325t_cm4.vhd'), os.path.join(here, 'avm_mig.vhd'),
          os.path.join(here, 'm65kbd_emu.vhd'), os.path.join(here, 'amiga_mouse.vhd'),
          os.path.join(here, 'amiga_fastram.vhd'), os.path.join(here, 'stall_ctrl.vhd'),
          os.path.join(here, 'mig_arb.vhd'), os.path.join(here, 'lat_meter.vhd'), os.path.join(here, 'chip_cache.vhd'), os.path.join(here, 'hdd_spi.vhd'), os.path.join(here, 'audio_fifo.vhd'),
          os.path.join(mc, 'sd_emu.vhdl'),
          os.path.join(mc, 'rk_bridge.vhdl'), os.path.join(mc, 'rk_iprog.vhdl')]:
    assert os.path.exists(f), f
    out.append('add_files -norecurse {%s}; set_property FILE_TYPE {VHDL 2008} [get_files {%s}]' % (f, f))
open(os.path.join(here, 'sources.tcl'), 'w').write('\n'.join(out) + '\n')
print('sources.tcl: %d files' % (len(out) - 1))
