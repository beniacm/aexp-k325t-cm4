#!/usr/bin/env python3
"""stubgen.py IN.v MODULE OUT.v -- a stub of a GHDL-generated module: the same parameters and ports,
every output tied to 0 (bench builds without the 68020 / the cache, for faster A500 runs)"""
import re, sys
s = open(sys.argv[1]).read()
i = s.index("module " + sys.argv[2] + "\n") if ("module " + sys.argv[2] + "\n") in s else s.index("module " + sys.argv[2])
j = s.index(");", i) + 2
hdr = s[i:j]
outs = re.findall(r"output\s+(?:reg\s+)?(?:\[[^\]]*\]\s*)?(\w+)", hdr)
body = "\n".join("  assign %s = 0;" % o for o in outs)
open(sys.argv[3], "w").write("// stub generated by stubgen.py (FAST_A500 bench build)\n" + hdr + "\n" + body + "\nendmodule\n")
